#!/usr/bin/env python3

import os
import random
import struct
import sys
import zlib

SIZE = 512


def png(w, h, rgba):
    def chunk(tag, data):
        return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xFFFFFFFF)
    stride = w * 4
    rows = b''.join(b'\x00' + rgba[y * stride:(y + 1) * stride] for y in range(h))
    return (b'\x89PNG\r\n\x1a\n'
            + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(rows, 1))
            + chunk(b'IEND', b''))


def main():
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 800
    rng = random.Random(1546990193)
    os.makedirs('icons', exist_ok=True)
    names = []
    for i in range(count):
        name = f'icons/icon{i:03d}.png'
        with open(name, 'wb') as f:
            f.write(png(SIZE, SIZE, rng.randbytes(SIZE * SIZE * 4)))
        names.append(name)
        if i % 100 == 99:
            print(f'  {i + 1}/{count} icons', flush=True)
    with open('icons.dm', 'w', newline='\n') as f:
        f.write('// Generated by make_icons.py.\n')
        f.write('var/global/list/test_icons = list(\n')
        f.write(',\n'.join(f"\t'{n}'" for n in names))
        f.write('\n)\n')
    print(f'wrote {count} icons and icons.dm')


if __name__ == '__main__':
    main()
